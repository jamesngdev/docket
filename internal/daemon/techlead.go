func (d *Daemon) startOrQueueTechlead(task string) error {
	if d.runningRole(agent.RoleTechLead) > 0 {
		if err := d.db.SetQueuedTask(task); err != nil {
			return err
		}
		d.db.Log("techlead", "busy; %s queued", task)
		return nil
	}
	return d.startTechlead(task)
}

// startQueuedTechlead runs the task queued while TechLead was busy (persisted in SQLite).
func (d *Daemon) startQueuedTechlead() {
	p, err := d.project()
	if err != nil || p.QueuedTask == "" || d.runningRole(agent.RoleTechLead) > 0 {
		return
	}
	_ = d.db.SetQueuedTask("")
	if err := d.startTechlead(p.QueuedTask); err != nil {
		d.db.Log("techlead", "queued %s: %v", p.QueuedTask, err)
	}
}

// startTechlead validates the pipeline gate for task and launches TechLead.
func (d *Daemon) startTechlead(task string) error {
	if d.runningRole(agent.RoleTechLead) > 0 {
		return fmt.Errorf("a TechLead run is already in progress")
	}
	p, err := d.project()
	if err != nil {
		return err
	}
	qs, _ := d.db.Questions()
	fs, _ := d.db.Features()
	ts, _ := d.db.Tickets()
	if err := gateCheck(task, qs, fs); err != nil {
		return err
	}
	if err := gitops.CheckoutBase(p.RepoPath, p.Settings.BaseBranch); err != nil {
		d.db.Log("techlead", "checkout %s: %v", p.Settings.BaseBranch, err)
	}
	_ = gitops.Pull(p.RepoPath)
	d.ensureCodegraph(p.RepoPath)

	docs, _ := d.db.Documents()
	third, _ := d.db.ThirdDocs()
	runID := agent.NewRunID(agent.RoleTechLead)
	ctxDir := d.paths.RunContext(runID)
	earlier, _ := d.db.FeatureTitlesOutsidePhase()
	in := agent.TechleadInput{Project: p, Task: task, Docs: docs, EarlierFeatures: earlier, PrevCommit: p.PrevDocsCommit, DocsHead: p.DocsCommit,
		Questions: qs, Features: fs, Tickets: ts}
	if err := agent.WriteFiles(ctxDir, map[string]string{
		"PROJECT.md": agent.ProjectMarkdown(in), "3TH_DOCUMENT.md": agent.ThirdDocsMarkdown(third),
	}); err != nil {
		return err
	}
	return d.launch(p, agent.RoleTechLead, task, runID, 0, p.RepoPath)
}

// gateCheck enforces the user approval gates before TechLead moves on.
func gateCheck(task string, qs []store.Question, fs []store.Feature) error {
	switch task {
	case agent.TaskBootstrap, agent.TaskDocDiff:
		return nil
	case agent.TaskFeatures:
		for _, q := range qs {
			if q.Status == store.QOpen {
				return fmt.Errorf("answer or skip all questions first")
			}
		}
		return nil
	case agent.TaskTickets:
		approved := 0
		for _, f := range fs {
			if f.Status == store.FDraft {
				return fmt.Errorf("approve or reject all draft features first")
			}
			if f.Status == store.FApproved {
				approved++
			}
		}
		if approved == 0 {
			return fmt.Errorf("no approved features")
		}
		return nil
	}
	return fmt.Errorf("unknown techlead task %q", task)
}

// ensureCodegraph indexes the repo on first use and syncs it afterwards.
func (d *Daemon) ensureCodegraph(repo string) {
	if !sh.Has("codegraph") {
		d.db.Log("codegraph", "codegraph not installed; agents fall back to plain reads")
		return
	}
	args := []string{"sync", repo}
	if _, err := os.Stat(filepath.Join(repo, ".codegraph")); os.IsNotExist(err) {
		args = []string{"init", "-y", repo}
	}
	if _, err := sh.Run(repo, "codegraph", args...); err != nil {
		d.db.Log("codegraph", "%s failed: %v", args[0], err)
	}
}

// composeUp starts the shared dev stack generated by TechLead.
func (d *Daemon) composeUp() error {
	p, err := d.project()
	if err != nil {
		return err
	}
	f := d.paths.ComposeFile()
	b, err := os.ReadFile(f)
	if err != nil {
		return fmt.Errorf("no %s yet (TechLead bootstrap creates it)", f)
	}
	var spec struct {
		Services map[string]any `yaml:"services"`
	}
	if err := yaml.Unmarshal(b, &spec); err != nil {
		return fmt.Errorf("invalid %s: %w", f, err)
	}
	if len(spec.Services) == 0 {
		d.db.Log("docker", "compose file defines no services; nothing to start")
		return nil
	}
	if _, err := sh.Run(d.paths.Root(), "docker", "compose", "-f", f, "-p", "po-"+p.Slug, "up", "-d"); err != nil {
		return err
	}
	d.db.Log("docker", "shared dev stack is up (project docket-%s)", p.Slug)
	return nil
}

func short(c string) string {
	if len(c) > 8 {
		return c[:8]
	}
	return c
}
